"""安全边界：高危信号词表。命中直接转就医，不进入 RAG 检索。"""

# 分三类：心血管/呼吸急症、脑血管（卒中预警）、其他急症。
# 判断标准："必须就医"级别，且普通工位放松建议对它有误导风险。
HIGH_RISK_TERMS = [
    # 心血管 / 呼吸急症
    "胸闷", "胸痛", "心慌", "心悸", "呼吸困难", "喘不上气", "气短", "憋气",
    # 脑血管（卒中）预警 —— 关键在"单侧/突然"
    "单侧无力", "半身麻木", "半边麻", "口角歪斜", "口齿不清", "说话不清",
    "剧烈头痛", "突然视物不清", "视野缺损",
    # 其他急症
    "单侧小腿肿痛", "咳血", "呕血",
]


def check_high_risk(query: str):
    """扫查询，命中高危词返回该词，未命中返回 None。"""
    for term in HIGH_RISK_TERMS:
        if term in query:
            return term
    return None
